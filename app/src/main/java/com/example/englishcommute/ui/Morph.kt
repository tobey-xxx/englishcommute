package com.example.englishcommute.ui

/**
 * 迷你播放条 ↔ 播放页的**共享元素形变**（Apple §7 空间连续性）。1.2.9 新增。
 *
 * ## 它要解决什么
 *
 * 「迷你条」和「播放页」在用户心里是**同一个东西的两个尺寸** —— 同一条内容、
 * 同一张封面、同一个播放状态。而在这一轮之前，用户点迷你条进入播放页时，
 * 播放页是「从下往上推上来」的，封面对封面之间没有任何联系：那张封面在
 * 底部长 40dp，然后「啪」地在顶部重新出现一次。
 *
 * §7 的要求是「交互要锚定到它的来源」。共享元素做的正是这件事：
 * 让底部那张封面**长成**顶部那张，中途由系统补间。
 *
 * ## ⚠️ 为什么这个常量存在（唯一一条可一键回退的路径）
 *
 * 这是全工程唯一用到**实验性 API** 的地方：`SharedTransitionLayout` +
 * `Modifier.sharedElement`（`@ExperimentalSharedTransitionApi`）。
 * 设计稿阶段就把这一处单独标出来让用户点头，理由有两条：
 *
 * 1. `SharedTransitionLayout` 内部是一个 `LookaheadScope`，它会给**整棵子树**
 *    多挂一次测量 pass —— 也就是说这个开关是「全局生效」的，不是局部的。
 *    对一个 LazyColumn 装 40 条内容的页面，这可能带来可感知的开销。
 * 2. 形变的手感只能在真机上看，桌面上验证不了。
 *
 * 所以：**把它改成 `false` 就是完整回退** —— 此时连 `SharedTransitionLayout`
 * 都不包（而不是「包着但不加 modifier」），LookaheadScope 的开销一并消失，
 * 其余界面完全不受影响（进出动画、下拉关闭都走各自独立的路径）。
 *
 * ## 共享的是什么
 *
 * 只共享**封面**，键 [MORPH_COVER_KEY]。
 *
 * 材质的整块展开（`sharedBounds`）**有意不做**：那会让迷你条那一整条
 * 变成播放页的整屏，中间态是一个「被拉伸的长条」，而播放页的布局
 * （顶栏 + 字幕 + 控制区）根本不是迷你条的等比放大 —— 那一段会很难看。
 * 封面是一张方图，两边只是尺寸不同，形变天然成立。
 */
internal const val SHARED_MORPH = true

/**
 * 封面共享元素的键。
 *
 * ⚠️ 两端必须是**同一个值**，所以只在这里定义一次：
 * 迷你条（常驻）与播放页顶栏（覆盖层）各引用它。
 *
 * 不带 episodeId 后缀：任意时刻只有一条在播，而这个键描述的是
 * 「迷你条和播放页上那个封面的身份」，不是某一条内容的身份。
 * 加上 id 反而会在切集时出现「旧键消失、新键出现」两个互不相干的形变。
 */
internal const val MORPH_COVER_KEY = "mini-cover"
