package com.example.englishcommute.word

/**
 * 底栏「生词」页签右上角那个角标上写什么。
 *
 * ## 「今天欠多少」这件事为什么要贴在底栏上
 *
 * 生词本是个**需要被推着做**的功能：用户加了词，但没有任何东西提醒他回去复习。
 * 打卡有 40 分钟的目标撑着，生词本没有 —— 不加提醒，它就是个只进不出的仓库。
 *
 * ## 为什么不做系统通知
 *
 * 通知是**打断**（用户正在做别的事，手机在兜里震一下）。而这里的诉求只是
 * 「我打开这个 App 的时候，知道有活等着」。两者的成本差一个数量级：
 * 通知要处理权限、渠道、静音时段、以及**和打卡提醒打架**
 * （同一个 App 一天推两条不同性质的提醒，用户会开始忽略所有推送）。
 *
 * 角标是「他打开 App 时顺便看到」，代价为零。这也正是这条需求写在
 * P2.4 而不是 P1 的原因。
 *
 * ## 为什么是数字，不是一个小圆点
 *
 * 圆点只回答「有没有」。而「3 个」和「47 个」决定的动作完全不同：
 * 前者是「现在花一分钟清掉」，后者是「我欠债了，得挑个时间坐下来」。
 * 这个 App 里另外几处也都在给具体数字（「今天要复习 N 个」「约 M 分钟」）
 * —— 用户是通勤路上决定「这一趟听什么」的人，抽象的信号对他没用。
 *
 * ## 为什么 0 返回 null 而不是 "0"
 *
 * 角标的意思是「有活等着」。`"0"` 是一个**看起来像回事但实际上什么也没说**
 * 的角标，而且它会永远挂在那里。**没有角标**才是「今天清爽了」的正确表达。
 *
 * ## 为什么封顶
 *
 * 断更一段时间之后，到期的卡片会堆起来（FSRS 的到期是按天算的，
 * 一周不看，一周的量全挤在同一天）。四位数会把底栏那一格撑变形。
 * `99+` 保住了「很多」这个信息，同时宽度只有三位。
 *
 * ⚠️ 这两个数（0 和 99）是**界面语义**，不是数据语义 —— 所以它们在这里，
 *    不在 [WordStore.dueCount] 里。`dueCount` 该是多少就是多少，
 *    「多少才值得显示成一个角标」是显示层的事。
 */
object DueBadge {

    /** 超过这个数就写 `99+`。见类注释最后一段 */
    const val CAP = 99

    /**
     * @param due [WordStore.dueCount] 的结果（今天 24:00 前到期的卡片数）
     * @return 角标文字；`null` = **不显示角标**
     */
    fun text(due: Int): String? = when {
        due <= 0 -> null
        due > CAP -> "$CAP+"
        else -> due.toString()
    }
}
